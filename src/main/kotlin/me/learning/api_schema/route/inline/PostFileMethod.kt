/**
 * Defines a POST route to handle file upload requests and process the uploaded file with the specified logic.
 *
 * The uploaded file is validated based on its extensions and passed to the provided processing block.
 * Optionally, the file can be deleted after processing is completed.
 *
 * @param T The type of the response generated by the processing block.
 * @param path The path for the POST route. Default is an empty string.
 * @param extensions The list of allowed file extensions for the uploaded file. Default is an empty list, meaning all extensions are allowed.
 * @param deleteAfterFinish Whether to delete the uploaded file after the processing block is completed. Default is false.
 * @param block A suspend lambda function to process the uploaded file. It receives a `FileInfoReq` object representing the file
 *               and produces a result of type `T`.
 * @return The configured Route.
 */
@JvmName("POST_FileInfoReq")
inline fun <reified T> Route.POSTFILE(
    path: String = "",
    extensions: List<String> = emptyList(),
    deleteAfterFinish: Boolean = false,
    crossinline block: suspend RoutingRequest.(file: FileInfoReq) -> T
): Route {
    val builder = schemaBuilder<T>(bodyAsFormData = true)

    return this.post(path, builder) {
        val request = call.getFileRequest(false, extensions).first()
        call.ok(call.request.block(request))
        if (deleteAfterFinish) request.file.delete()
    }
}


/**
 * Defines a POST route for handling file uploads with authorization and custom logic.
 * The route processes a multipart form-data request, extracts the uploaded file with validation,
 * invokes the provided logic block, and returns a response.
 *
 * @param T The type of the response to be returned by the route.
 * @param I The type of the authorization data required for the route.
 * @param path The URI path at which the route will be registered. Defaults to an empty string,
 * meaning the route will be registered at the current path.
 * @param extensions A list of allowed file extensions for the upload. If empty, all file types are allowed.
 * @param deleteAfterFinish A flag indicating whether the uploaded file should be deleted after the route processing is complete.
 * Defaults to false, meaning the file will not be deleted.
 * @param block A suspending lambda function representing the custom processing logic for the uploaded file.
 * It takes the authorization data and the uploaded file information as arguments and returns a response of type T.
 * @return The configured Route object.
 */
@JvmName("POST_Auth_FileInfoReq")
inline fun <reified T, reified I : Any> Route.POSTFILE(
    path: String = "",
    extensions: List<String> = emptyList(),
    deleteAfterFinish: Boolean = false,
    crossinline block: suspend RoutingRequest.(auth: I, file: FileInfoReq) -> T
): Route {
    val builder = schemaBuilder<T>(bodyAsFormData = true)

    return this.post(path, builder) {
        val auth = call.auth<I>()
        val request = call.getFileRequest(false, extensions).first()
        call.ok(call.request.block(auth, request))
        if (deleteAfterFinish) request.file.delete()
    }
}


