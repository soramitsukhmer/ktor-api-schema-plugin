/**
 * Defines a HTTP POST route that accepts a file upload and a data payload, processes them, and executes
 * a custom action defined by the user.
 *
 * @param T The type of the returned response from the lambda block.
 * @param I The type of the additional data payload received in the form-data request.
 * @param path The path of the route (endpoint) where this method applies. Default is an empty string.
 * @param extensions A list of file extensions allowed for the uploaded files. Default is an empty list.
 * @param deleteAfterFinish Whether to delete the uploaded files from the server after the processing is completed.
 * Default is false.
 * @param block A lambda function that handles the received file and data payload. It receives the uploaded
 * file (`FileInfoReq`) and deserialized payload of type `I` as parameters and returns a value of type `T`.
 * @return The configured `Route` object for the specified endpoint.
 */
@JvmName("POST_FileInfoReq_Data")
inline fun <reified T, reified I> Route.POSTFILE(
    path: String = "",
    extensions: List<String> = emptyList(),
    deleteAfterFinish: Boolean = false,
    crossinline block: suspend RoutingRequest.(file: FileInfoReq, data: I) -> T
): Route {
    MethodEnum.POST.throwOnFileOrListTypeReqBody<I>(path)
    val builder = schemaBuilder<T>(bodyAsFormData = true, bodyFileAsList = true)

    return this.post(path, builder) {
        val (files, request) = call.getFileDataRequest<I>(false, extensions)
        call.ok(call.request.block(files.first(), request))
        if (deleteAfterFinish) files.forEach { it.file.delete() }
    }
}


